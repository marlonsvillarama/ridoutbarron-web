<p class="summary">
    There are many important events in your life which require you to consider drafting or revising your estate documents, including your Will, your Enduring Power of Attorney and your Personal Directive.
</p>

<p>
    For instance:
</p>
<ol>
    <li>the purchase or sale of a home or other significant asset</li>
    <li>new ownership of a business</li>
    <li>birth or adoption of a child or grandchild</li>
    <li>death of a family member</li>
    <li>marriage</li>
    <li>separation or divorce</li>
    <li>travel</li>
</ol>

<p>
    If you've ever purchased a home, started a business, cared for a loved one or even lost a loved one, you probably understand that there are many legal aspects to something that appears to be straightforward. These are all important times in your life and we would like you consider directing your thoughts to your estate.
</p>
<p>
    It doesn't matter if you are old or young, single or married, or have children or grandchildren. There are many legal complexities when dealing with Wills and Estates, and we can help. We have prepared hundreds of Wills, Powers of Attorney and Personal Directives over the years.
</p>
